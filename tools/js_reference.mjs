// Writes game/tests/data/js_reference.json: reference outputs from the design's
// own JavaScript (design/shared/*.js), so the GDScript ports can be checked
// against it. Run with node when design/shared changes:
//
//     node tools/js_reference.mjs
//
// The JSON is committed, so the tests don't need node.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ctx = {
  location: { search: "" }, URLSearchParams, Math, console,
  document: { documentElement: { classList: { contains: () => false } } },
  matchMedia: () => ({ matches: false }),
};
ctx.window = ctx;
vm.createContext(ctx);
for (const f of ["board.js", "screens.js", "fx.js"]) {
  vm.runInContext(readFileSync(join(root, "design/shared", f), "utf8"), ctx, { filename: f });
}
const { CS, FX } = ctx;

// HUD panels: [seed as CS.jagAll computes it, width, height] for gameplay and game over.
const panels = [[14, 362, 112], [33, 620, 120], [22, 330, 160], [55, 250, 124], [48, 284, 236], [79, 800, 50],
  [6, 1000, 520], [19, 600, 420], [3, 200, 60], [91, 140, 40]];
const jag = panels.map(([seed, w, h]) => ({ seed, w, h, ...CS.jagPoints(w, h, seed) }));

const hash2 = [];
for (const [x, y, s] of [[0, 0, 0], [1, 2, 3], [14, 7, 11], [-5, 9, 99], [1000, -1000, 5], [123456, 654321, 2147483647]]) {
  hash2.push({ x, y, s, v: CS.hash2(x, y, s) });
}

const plans = [];
for (let seed = 0; seed < 200; seed++) plans.push(FX.breachPlan(seed * 7919 + 13));
for (const kind of ["clean", "one", "99", "double"]) plans.push({ forced: kind, ...FX.breachPlan(424242, kind) });
const strip = (p) => ({ seed: p.seed, forced: p.forced || "", kind: p.kind, total: p.total, key: p.key,
  stalls: p.stalls, segs: p.segs.map((g) => ({ t0: g.t0, t1: g.t1, p0: g.p0, p1: g.p1, denied: !!g.denied })) });

const out = { _about: "Generated by tools/js_reference.mjs from design/shared/*.js. Don't edit by hand.",
  T: FX.T, boot_lines: FX.BOOT_LINES, hash2, jag, plans: plans.map(strip) };
writeFileSync(join(root, "game/tests/data/js_reference.json"), JSON.stringify(out, null, 1) + "\n");
console.log(`wrote ${jag.length} jag panels, ${plans.length} breach plans`);
